const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const nodes=Object.fromEntries(['manualsOrders','manualsSearch','manualsHistory','manualsCount'].map(id=>[id,{value:'',checked:false}]));
const data={orders:[{id:'a',name:'194044',productNr:'007142',productName:'SKSM <80>',line:'H1',subgroup:'SKSM',archived:false},{id:'b',name:'194050',productNr:'006863',productName:'SKSM 80 S',archived:true}]};
const before=JSON.stringify(data);let selected;
const context=vm.createContext({data,$:id=>nodes[id],current:()=>data.orders[0],esc:v=>String(v).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;'),selectOrder:id=>selected=id});
vm.runInContext(fs.readFileSync('manuals.js','utf8'),context);
assert.match(nodes.manualsOrders.innerHTML,/194044/);assert.doesNotMatch(nodes.manualsOrders.innerHTML,/194050/);
assert.match(nodes.manualsOrders.innerHTML,/SKSM &lt;80&gt;/);
nodes.manualsHistory.checked=true;nodes.manualsHistory.onchange();assert.match(nodes.manualsOrders.innerHTML,/194050/);
nodes.manualsSearch.value='006863';nodes.manualsSearch.oninput();assert.doesNotMatch(nodes.manualsOrders.innerHTML,/194044/);
nodes.manualsSearch.value='finns-inte';nodes.manualsSearch.oninput();assert.match(nodes.manualsOrders.innerHTML,/Ingen order matchar/);
nodes.manualsOrders.onclick({target:{closest:()=>({dataset:{manualOrder:'a'}})}});assert.equal(selected,'a');
assert.equal(JSON.stringify(data),before);
const html=fs.readFileSync('index.html','utf8');assert.equal((html.match(/data-view="manuals"/g)||[]).length,4);
assert.match(fs.readFileSync('app.js','utf8'),/manualsView.*next!=='manuals'/);
const sw=fs.readFileSync('sw.js','utf8');assert.match(sw,/\/manuals.js/);assert.match(sw,/\/manuals.css/);
console.log('Manuals: navigation, order search, archive filter, escaping, empty states and data preservation passed');
